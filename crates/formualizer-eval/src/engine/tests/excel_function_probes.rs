//! Excel for Windows 16.0.20430's values for the functions of round 6 (MDETERM, MINVERSE,
//! MUNIT, PERMUTATIONA, PROB, PERCENTOF, AREAS, ISOMITTED and optional LAMBDA parameters,
//! ENCODEURL, BAHTTEXT, TRIMRANGE and the trim operators, REGEXTEST, REGEXEXTRACT,
//! REGEXREPLACE and the FORECAST.ETS family): every row of
//! ops/excel-functions-probe-20261006.md the fork follows, each formula as Excel saved it,
//! in F1 (or the first cell of the range it spills to) of a sheet whose Z1 holds the
//! recorder's =1111+2222. Numbers to 1e-12 relative, errors by kind, a spill cell by cell.
//! The rows the fork does not follow are listed in the record with the reason.

use crate::engine::{Engine, EvalConfig};
use crate::test_workbook::TestWorkbook;
use formualizer_common::{ExcelErrorKind, LiteralValue};
use formualizer_parse::parser::parse;

/// A cell set before the formula: a number, text, a logical or a formula.
enum S {
    N(f64),
    T(&'static str),
    B(bool),
    F(&'static str),
}

/// An expected cell.
enum V {
    N(f64),
    T(&'static str),
    B(bool),
    E(ExcelErrorKind),
    Blank,
}

type Case = (
    &'static str,
    &'static [(&'static str, S)],
    &'static str,
    &'static [&'static [V]],
);

fn cell(address: &str) -> (u32, u32) {
    let letters: String = address
        .chars()
        .take_while(|c| c.is_ascii_alphabetic())
        .collect();
    let row = address[letters.len()..].parse().unwrap();
    let col = letters
        .bytes()
        .fold(0, |acc, b| acc * 26 + u32::from(b - b'A' + 1));
    (row, col)
}

fn matches(actual: Option<&LiteralValue>, expected: &V) -> bool {
    match (actual, expected) {
        (None | Some(LiteralValue::Empty), V::Blank) => true,
        (Some(LiteralValue::Number(a)), V::N(b)) => a == b || (a - b).abs() <= 1e-12 * b.abs(),
        (Some(LiteralValue::Int(a)), V::N(b)) => *a as f64 == *b,
        (Some(LiteralValue::Text(a)), V::T(b)) => a == b,
        (Some(LiteralValue::Boolean(a)), V::B(b)) => a == b,
        (Some(LiteralValue::Error(a)), V::E(b)) => a.kind == *b,
        _ => false,
    }
}

fn check(cases: &[Case]) {
    let mut failures = Vec::new();
    for (formula, setup, range, expected) in cases {
        let mut engine = Engine::new(TestWorkbook::new(), EvalConfig::default());
        for (address, value) in setup.iter() {
            let (row, col) = cell(address);
            match value {
                S::N(n) => engine.set_cell_value("Sheet1", row, col, LiteralValue::Number(*n)),
                S::T(t) => {
                    engine.set_cell_value("Sheet1", row, col, LiteralValue::Text((*t).into()))
                }
                S::B(b) => engine.set_cell_value("Sheet1", row, col, LiteralValue::Boolean(*b)),
                S::F(f) => engine.set_cell_formula("Sheet1", row, col, parse(f).unwrap()),
            }
            .unwrap();
        }
        engine
            .set_cell_formula("Sheet1", 1, 26, parse("=1111+2222").unwrap())
            .unwrap();
        let (top, left) = cell(range.split(':').next().unwrap());
        engine
            .set_cell_formula("Sheet1", top, left, parse(formula).unwrap())
            .unwrap_or_else(|e| panic!("{formula}: {e:?}"));
        engine.evaluate_all().unwrap();
        for (r, row) in expected.iter().enumerate() {
            for (c, want) in row.iter().enumerate() {
                let got = engine.get_cell_value("Sheet1", top + r as u32, left + c as u32);
                if !matches(got.as_ref(), want) {
                    failures.push(format!("{formula} at +{r},+{c}: {got:?}"));
                }
            }
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

