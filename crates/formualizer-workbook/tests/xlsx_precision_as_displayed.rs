/// A cell: its address; its number format, a code or `#N` for built-in
/// format N; its content: `=` and a formula, `{ref}=` or `{ref}#=` for a
/// legacy or dynamic array formula over `ref`, nothing for an array member,
/// else a number; and the value Excel stored, if a formula's: a number,
/// `TRUE`/`FALSE`, an error or `'` and text.
type Cell = (&'static str, &'static str, &'static str, &'static str);

fn escape(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

fn position(address: &str) -> (u32, u32) {
    let letters = address.trim_end_matches(|c: char| c.is_ascii_digit());
    let col = letters
        .bytes()
        .fold(0, |n, b| n * 26 + u32::from(b - b'A') + 1);
    (address[letters.len()..].parse().unwrap(), col)
}

/// The package of `cells` on Sheet1, with precision as displayed on or off.
fn package(cells: &[(String, String, String)], precision_as_displayed: bool) -> Vec<u8> {
    let mut ids: BTreeMap<String, u32> = BTreeMap::new();
    let mut custom = String::new();
    let mut xfs = vec![0u32];
    let mut style = |format: &str| -> usize {
        let id = match format.strip_prefix('#').and_then(|n| n.parse().ok()) {
            Some(id) => id,
            None if format == "General" => 0,
            None => {
                let next = 164 + ids.len() as u32;
                *ids.entry(format.to_owned()).or_insert_with(|| {
                    custom.push_str(&format!(
                        "<numFmt numFmtId=\"{next}\" formatCode=\"{}\"/>",
                        escape(format)
                    ));
                    next
                })
            }
        };
        match xfs.iter().position(|xf| *xf == id) {
            Some(index) => index,
            None => {
                xfs.push(id);
                xfs.len() - 1
            }
        }
    };
    let mut rows: BTreeMap<u32, Vec<(u32, String)>> = BTreeMap::new();
    let mut dynamic = false;
    for (address, format, content) in cells {
        let s = style(format);
        let (row, col) = position(address);
        let xml = if let Some(rest) = content.strip_prefix('{') {
            let (area, formula) = rest.split_once('}').unwrap();
            let (cm, formula) = match formula.strip_prefix('#') {
                Some(formula) => (" cm=\"1\"", formula),
                None => ("", formula),
            };
            dynamic |= !cm.is_empty();
            let formula = formula.strip_prefix('=').unwrap();
            format!(
                "<c r=\"{address}\" s=\"{s}\"{cm}><f t=\"array\" ref=\"{area}\">{}</f></c>",
                escape(formula)
            )
        } else if let Some(formula) = content.strip_prefix('=') {
            format!(
                "<c r=\"{address}\" s=\"{s}\"><f>{}</f></c>",
                escape(formula)
            )
        } else if content.is_empty() {
            format!("<c r=\"{address}\" s=\"{s}\"><v>0</v></c>")
        } else {
            format!("<c r=\"{address}\" s=\"{s}\"><v>{content}</v></c>")
        };
        rows.entry(row).or_default().push((col, xml));
    }
    let sheet: String = rows
        .into_iter()
        .map(|(row, mut cells)| {
            cells.sort();
            let cells: String = cells.into_iter().map(|(_, xml)| xml).collect();
            format!("<row r=\"{row}\">{cells}</row>")
        })
        .collect();
    let numfmts = if ids.is_empty() {
        String::new()
    } else {
        format!("<numFmts count=\"{}\">{custom}</numFmts>", ids.len())
    };
    let xfs: String = xfs
        .iter()
        .map(|id| {
            format!("<xf numFmtId=\"{id}\" fontId=\"0\" fillId=\"0\" borderId=\"0\" xfId=\"0\"/>")
        })
        .collect();
    let styles = format!(
        "<styleSheet xmlns=\"{MAIN}\">{numfmts}<fonts count=\"1\"><font/></fonts><fills count=\"1\"><fill/></fills><borders count=\"1\"><border/></borders><cellStyleXfs count=\"1\"><xf numFmtId=\"0\" fontId=\"0\" fillId=\"0\" borderId=\"0\"/></cellStyleXfs><cellXfs>{xfs}</cellXfs></styleSheet>"
    );
    let calc = if precision_as_displayed {
        "<calcPr calcId=\"191029\" fullPrecision=\"0\"/>"
    } else {
        "<calcPr calcId=\"191029\"/>"
    };
    let (metadata_type, metadata_rel) = if dynamic {
        (
            "<Override PartName=\"/xl/metadata.xml\" ContentType=\"application/vnd.openxmlformats-officedocument.spreadsheetml.sheetMetadata+xml\"/>".to_owned(),
            format!("<Relationship Id=\"rId3\" Type=\"{OFFICE}/sheetMetadata\" Target=\"metadata.xml\"/>"),
        )
    } else {
        (String::new(), String::new())
    };
    let mut parts = vec![
        (
            "[Content_Types].xml".to_owned(),
            format!(
                "<Types xmlns=\"http://schemas.openxmlformats.org/package/2006/content-types\"><Default Extension=\"rels\" ContentType=\"application/vnd.openxmlformats-package.relationships+xml\"/><Default Extension=\"xml\" ContentType=\"application/xml\"/><Override PartName=\"/xl/workbook.xml\" ContentType=\"application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml\"/><Override PartName=\"/xl/worksheets/sheet1.xml\" ContentType=\"application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml\"/><Override PartName=\"/xl/styles.xml\" ContentType=\"application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml\"/>{metadata_type}</Types>"
            ),
        ),
        (
            "_rels/.rels".to_owned(),
            format!(
                "<Relationships xmlns=\"{RELS}\"><Relationship Id=\"rId1\" Type=\"{OFFICE}/officeDocument\" Target=\"xl/workbook.xml\"/></Relationships>"
            ),
        ),
        (
            "xl/workbook.xml".to_owned(),
            format!(
                "<workbook xmlns=\"{MAIN}\" xmlns:r=\"{OFFICE}\"><sheets><sheet name=\"Sheet1\" sheetId=\"1\" r:id=\"rId1\"/></sheets>{calc}</workbook>"
            ),
        ),
        (
            "xl/_rels/workbook.xml.rels".to_owned(),
            format!(
                "<Relationships xmlns=\"{RELS}\"><Relationship Id=\"rId1\" Type=\"{OFFICE}/worksheet\" Target=\"worksheets/sheet1.xml\"/><Relationship Id=\"rId2\" Type=\"{OFFICE}/styles\" Target=\"styles.xml\"/>{metadata_rel}</Relationships>"
            ),
        ),
        ("xl/styles.xml".to_owned(), styles),
        (
            "xl/worksheets/sheet1.xml".to_owned(),
            format!("<worksheet xmlns=\"{MAIN}\"><sheetData>{sheet}</sheetData></worksheet>"),
        ),
    ];
    if dynamic {
        parts.push(("xl/metadata.xml".to_owned(), format!("<metadata xmlns=\"{MAIN}\" xmlns:xda=\"http://schemas.microsoft.com/office/spreadsheetml/2017/dynamicarray\">{XLDAPR}</metadata>")));
    }
    let mut zip = zip::ZipWriter::new(Cursor::new(Vec::new()));
    for (name, body) in parts {
        zip.start_file(name, zip::write::SimpleFileOptions::default())
            .unwrap();
        zip.write_all(body.as_bytes()).unwrap();
    }
    zip.finish().unwrap().into_inner()
}

/// Recalculate `cells` and compare every stored value with Excel's.
fn check(case: &str, cells: &[(String, String, String, String)], precision_as_displayed: bool) {
    let input: Vec<_> = cells
        .iter()
        .map(|(a, f, c, _)| (a.clone(), f.clone(), c.clone()))
        .collect();
    let out = recalculate_xlsx_bytes(
        &package(&input, precision_as_displayed),
        XlsxRecalculateOptions::default(),
    )
    .unwrap_or_else(|error| panic!("{case}: {error}"));
    let mut book = Xlsx::new(Cursor::new(out.bytes)).unwrap();
    let range = book.worksheet_range("Sheet1").unwrap();
    let mut wrong = Vec::new();
    for (address, format, content, excel) in cells {
        if excel.is_empty() {
            continue;
        }
        let (row, col) = position(address);
        let got = range
            .get_value((row - 1, col - 1))
            .cloned()
            .unwrap_or(Data::Empty);
        let same = match (excel.as_str(), &got) {
            ("TRUE", Data::Bool(b)) => *b,
            ("FALSE", Data::Bool(b)) => !*b,
            (e, Data::Error(error)) if e.starts_with('#') => format!("{error}") == e,
            (e, Data::String(text)) if e.starts_with('\'') => &e[1..] == text,
            (e, Data::Float(n)) => e.parse::<f64>().is_ok_and(|x| x.to_bits() == n.to_bits()),
            // A number in a cell with a date or time format.
            (e, Data::DateTime(n)) => e
                .parse::<f64>()
                .is_ok_and(|x| x.to_bits() == n.as_f64().to_bits()),
            (e, Data::Int(n)) => e.parse::<f64>().is_ok_and(|x| x == *n as f64),
            _ => false,
        };
        if !same {
            wrong.push(format!(
                "{address} [{format}] {content}: Excel {excel}, fork {got:?}"
            ));
        }
    }
    assert!(wrong.is_empty(), "{case}:\n{}", wrong.join("\n"));
}

/// The cells of a grid case: A1:An hold `values` under `format`, B1:Bn
/// (when Excel's are given) `=An*1` in General.
fn grid_cells(
    values: &[&str],
    format: &str,
    stored: &[&str],
    dependents: &[&str],
) -> Vec<(String, String, String, String)> {
    let mut cells = Vec::new();
    for (i, (value, excel)) in values.iter().zip(stored).enumerate() {
        let row = i + 1;
        cells.push((
            format!("A{row}"),
            format.to_owned(),
            format!("={value}"),
            (*excel).to_owned(),
        ));
        if let Some(excel) = dependents.get(i) {
            cells.push((
                format!("B{row}"),
                "General".to_owned(),
                format!("=A{row}*1"),
                (*excel).to_owned(),
            ));
        }
    }
    cells
}

fn owned(cells: &[Cell]) -> Vec<(String, String, String, String)> {
    cells
        .iter()
        .map(|(a, f, c, e)| {
            (
                (*a).to_owned(),
                (*f).to_owned(),
                (*c).to_owned(),
                (*e).to_owned(),
            )
        })
        .collect()
}

